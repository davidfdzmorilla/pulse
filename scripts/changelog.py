#!/usr/bin/env python3
"""Writes the released part of CHANGELOG.md from Pulse's GitHub releases.

Each release's notes are the titles of the pull requests merged into it (see
scripts/release.sh), in Spanish, exactly as the app shows them. They are
copied as they are, never rewritten or sorted into categories by guesswork.
The "Unreleased" section at the top of CHANGELOG.md is kept by hand and left
untouched.

Usage (needs the GitHub CLI, `gh`, signed in or not):
    python3 scripts/changelog.py            # rewrites CHANGELOG.md
    python3 scripts/changelog.py --check    # exits 1 if it is out of date
"""
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = "davidfdzmorilla/pulse"
ROOT = Path(__file__).resolve().parent.parent
CHANGELOG = ROOT / "CHANGELOG.md"
MARKER = "<!-- Released versions below are generated by scripts/changelog.py from the GitHub releases. Don't edit them by hand. -->"
VERSION = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


def releases():
    out = subprocess.run(["gh", "api", "--paginate", f"repos/{REPO}/releases?per_page=100"], check=True, capture_output=True, text=True).stdout
    # --paginate concatenates one JSON array per page.
    found = []
    for page in re.split(r"(?<=\])\s*(?=\[)", out.strip()):
        found += json.loads(page)
    found = [r for r in found if VERSION.match(r["tag_name"]) and not r["draft"] and not r["prerelease"]]
    found.sort(key=lambda r: tuple(int(n) for n in VERSION.match(r["tag_name"]).groups()), reverse=True)
    return found


def released_part():
    lines = [MARKER, ""]
    for r in releases():
        version = r["tag_name"][1:]
        date = (r["published_at"] or r["created_at"])[:10]
        lines.append(f"## [{version}](https://github.com/{REPO}/releases/tag/{r['tag_name']}) - {date}")
        lines.append("")
        body = (r["body"] or "").strip().replace("\r\n", "\n")
        lines.append(body if body else "- (sin notas)")
        lines.append("")
    return "\n".join(lines)


def main():
    text = CHANGELOG.read_text()
    if MARKER not in text:
        sys.exit(f"{CHANGELOG} has no generated-part marker")
    head = text[: text.index(MARKER)]
    new = head + released_part()
    if "--check" in sys.argv:
        if new != text:
            sys.exit("CHANGELOG.md is out of date: run python3 scripts/changelog.py")
        return
    CHANGELOG.write_text(new)
    print(f"{CHANGELOG.name}: {new.count('## [')} versions")


if __name__ == "__main__":
    main()
