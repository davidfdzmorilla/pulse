# Not crates: what Pulse links in or runs besides them.
OTHERS = [
    ("ONNX Runtime (Microsoft), enlazado en Pulse por el crate ort", "packaging/notices/ONNXRUNTIME_LICENSE"),
    ("Beat This! (modelos de tempo y compás)", "crates/beats/models/LICENSE"),
    ("Basic Pitch (Convertir a MIDI)", "crates/stems/models/BASIC_PITCH_NOTICE"),
    ("Modelo de batería de Pulse (datos de entrenamiento)", "crates/stems/models/DRUMS_NOTICE"),
    ("Whisper small (Transcribir letra; se descarga al usarlo)", "crates/stems/models/WHISPER_NOTICE"),
    ("HTDemucs (Separar en stems; se descarga la primera vez)", "packaging/notices/HTDEMUCS_LICENSE"),
]


def choose(expression):
    """The licences a crate without licence files is given."""
    expression = expression.replace("/", " OR ")
    parts = [p.strip(" ()") for p in re.split(r"\bAND\b", expression)]
    chosen = []
    for part in parts:
        options = [o.strip(" ()") for o in re.split(r"\bOR\b", part)]
        options = [o.split(" WITH ")[0].strip() for o in options]
        best = sorted(options, key=lambda o: PREFERENCE.index(o) if o in PREFERENCE else len(PREFERENCE))[0]
        chosen.append(best)
    return chosen


def find_apache(packages):
    for p in packages:
        folder = os.path.dirname(p["manifest_path"])
        for name in ("LICENSE-APACHE", "LICENSE-APACHE2", "LICENSE-Apache-2.0"):
            path = os.path.join(folder, name)
            if os.path.isfile(path):
                text = open(path, encoding="utf-8", errors="replace").read()
                if "TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION" in text:
                    return text
    sys.exit("No Apache-2.0 text found among the crates")


def normal(text):
    return re.sub(r"\s+", " ", text).strip()


def main():
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True).stdout)
    members = set(metadata["workspace_members"])
    packages = sorted((p for p in metadata["packages"] if p["id"] not in members), key=lambda p: (p["name"], p["version"]))
    apache = find_apache(packages)

    texts = {}  # normalised text -> (text, [crates])
    missing = []
    for p in packages:
        folder = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(folder) if LICENCE_FILE.match(f) and os.path.isfile(os.path.join(folder, f)))
        if p.get("license_file"):
            files.append(p["license_file"])
        # Fonts with licences of their own (egui's), besides the crate's.
        fonts = os.path.join(folder, "fonts")
        font_files = [os.path.join("fonts", f) for f in sorted(os.listdir(fonts)) if f.endswith(".txt")] if os.path.isdir(fonts) else []
        bodies = []
        for f in dict.fromkeys(files + font_files):
            bodies.append(open(os.path.join(folder, f), encoding="utf-8", errors="replace").read())
        if not files:
            authors = ", ".join(re.sub(r"\s*<[^>]*>", "", a) for a in p.get("authors") or []) or f"the {p['name']} developers"
            for licence in choose(p.get("license") or ""):
                if font_files and licence in FONT_LICENCES:
                    continue
                if licence == "MIT":
                    bodies.append(MIT.format(authors=authors))
                elif licence == "Apache-2.0":
                    bodies.append(apache)
                elif licence == "BSL-1.0":
                    bodies.append(BSL.format(authors=authors))
                else:
                    missing.append(f"{p['name']} {p['version']}: {licence}")
        label = f"{p['name']} {p['version']} ({p.get('license') or 'sin licencia declarada'})"
        if p.get("repository"):
            label += f" {p['repository']}"
        for body in bodies:
            key = normal(body)
            texts.setdefault(key, (body.strip(), []))[1].append(label)
    if missing:
        sys.exit("No text for:\n  " + "\n  ".join(missing))

    out = []
    out.append("Pulse: avisos de terceros / third-party notices\n")
    out.append("Pulse es software libre bajo la GNU General Public License v3.0 o posterior\n"
               "(ver LICENSE). Incluye los componentes de abajo, cada uno con su licencia.\n"
               "Este archivo lo genera scripts/notices.py.\n")
    out.append("=" * 78 + "\nComponentes que no son crates de Rust\n" + "=" * 78 + "\n")
    for title, path in OTHERS:
        out.append("-" * 78 + f"\n{title}\n" + "-" * 78 + "\n")
        out.append(open(os.path.join(ROOT, path), encoding="utf-8").read().strip() + "\n")
    out.append("=" * 78 + f"\nCrates de Rust ({len(packages)}, de Cargo.lock)\n" + "=" * 78 + "\n")
    for body, crates in sorted(texts.values(), key=lambda t: t[1][0]):
        out.append("-" * 78 + "\n" + "\n".join(crates) + "\n" + "-" * 78 + "\n")
        out.append(body + "\n")
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"{OUT}: {len(packages)} crates, {len(texts)} textos, {os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
