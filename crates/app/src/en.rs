    /// The engine's texts that the devices show through `tr`, all of them in
    /// Spanish: modes, spaces, carriers, chords and keyboard models.
    fn engine_texts() -> BTreeSet<String> {
        use engine::model::{KeysModel, ReverbSpace, TransitionMode, VocoderCarrier, VocoderChord};
        let mut texts: Vec<&str> = Vec::new();
        texts.extend(TransitionMode::ALL.map(|m| m.label()));
        texts.extend(ReverbSpace::ALL.iter().flat_map(|s| [s.label(), s.hint()]));
        texts.extend(VocoderCarrier::ALL.map(|c| c.label()));
        texts.extend(VocoderChord::ALL.map(|c| c.label()));
        texts.extend(KeysModel::ALL.iter().flat_map(|m| [m.label(), m.hint()]));
        // The chord track's progressions, for a major key and a minor one.
        for minor in [false, true] {
            texts.extend(stems::chord::progressions(stems::key::Key { tonic: 0, minor }).iter().map(|p| p.name));
        }
        texts.into_iter().map(str::to_string).collect()
    }

    /// Names the devices also show through `tr` but mostly in English already
    /// (effects, parameters, drum machines and their sounds): the Spanish ones
    /// have their pair here, the others show as they are.
    fn engine_names() -> BTreeSet<String> {
        use engine::model::{DrumModel, Effect, InstrumentKind};
        let mut names: Vec<&str> = Vec::new();
        for effect in Effect::catalog() {
            names.push(effect.label());
            names.extend(effect.params().iter().map(|p| p.name));
        }
        for kind in InstrumentKind::catalog() {
            names.extend(kind.params().iter().map(|p| p.name));
        }
        names.extend(engine::model::MidiEffect::catalog().iter().map(|e| e.label()));
        names.extend(DrumModel::ALL.map(|m| m.label()));
        names.extend((0..engine::model::DRUM_SOUNDS).map(crate::project::voice_name));
        names.into_iter().map(str::to_string).collect()
    }

    /// The parts of Pulse's own names that `i18n::tr_name` shows: factory
    /// presets, chains, kits and «Sonidos de Pulse». Each one needs its pair,
    /// unless it is the same in English (`SAME_IN_ENGLISH`).
    fn pulse_names() -> BTreeSet<String> {
        use engine::model::{Effect, InstrumentKind};
        let mut names: Vec<String> = Vec::new();
        for kind in InstrumentKind::catalog() {
            names.extend(crate::presets::factory(&kind).into_iter().map(|p| p.name));
        }
        for effect in Effect::catalog() {
            names.extend(effect.factory_presets().into_iter().map(|(n, _)| n.to_string()));
        }
        names.extend(crate::chains::factory().into_iter().map(|c| c.name));
        for recipe in crate::factory_recipes::recipes() {
            names.push(recipe.folder.to_string());
            names.push(recipe.name.to_string());
        }
        names.extend([crate::factory_sounds::NAME, crate::factory_sounds::KITS, crate::factory_sounds::LOOPS, "General"].map(str::to_string));
        names.iter().flat_map(|n| n.split(" · ")).filter(|p| !SAME_IN_ENGLISH.contains(p)).map(str::to_string).collect()
    }

