import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "packaging", "THIRD_PARTY_NOTICES.txt")

LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)", re.I)
# What a crate without licence files is given, in order of preference.
FONT_LICENCES = {"OFL-1.1", "Ubuntu-font-1.0"}
