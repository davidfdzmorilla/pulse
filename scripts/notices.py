#!/usr/bin/env python3
"""Writes packaging/THIRD_PARTY_NOTICES.txt: the licences of everything Pulse
carries that isn't Pulse's (Cargo.lock's crates, ONNX Runtime, the AI models and
the fonts egui brings). pulse.exe and Pulse.app show it in «Acerca de Pulse» and
both packages ship it. Run it again after changing dependencies (a test checks
that every crate in Cargo.lock is listed):

    python3 scripts/notices.py

Each crate's own licence files are copied as they are. A crate that ships none
gets the standard text of its licence (MIT when it offers a choice) with the
authors from its Cargo.toml. Identical texts are written once, with every
crate that uses them.
"""

